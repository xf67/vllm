#!/usr/bin/env python3
"""Generate paper-style matplotlib plots for online benchmark results.

This script scans benchmark result directories generated by the online
experiments, parses condition names from directory names, and plots:

1. An overview figure with one subplot per workload.
2. One standalone figure per workload.

Each line corresponds to one online test condition. Colors are reserved for
different scheduling strategies, while line styles distinguish different QoS
distribution settings.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


RESULT_ROOT = Path("/home/xxf/NewVLLM/vllm/test-vllm-ok/bench_results")
DEFAULT_OUTPUT_DIR = Path("/home/xxf/NewVLLM/vllm/test-vllm-ok/paper_figs/online")

EXPERIMENT_NAME_RE = re.compile(
    r"^(?P<workload>.+)-online_(?P<strategy>[^-]+)-(?P<dist>m\d+s\d+)-r(?P<rate>.+)$"
)
DIST_RE = re.compile(r"^m(?P<mean>\d+)s(?P<std>\d+)$")

STRATEGY_LABELS = {
    "ours": "Ours",
    "vllmD": "vLLM",
    "vllmK": "vLLM + QoS",
    "vllmT": "vLLM-TP",
}

STRATEGY_ORDER = ["ours", "vllmK", "vllmD", "vllmT"]
COLOR_MAP = {
    "ours": "#d62728",
    "vllmK": "#1f77b4",
    "vllmD": "#2ca02c",
    "vllmT": "#9467bd",
}
MARKER_MAP = {
    "ours": "o",
    "vllmK": "s",
    "vllmD": "^",
    "vllmT": "D",
}
LINESTYLE_CYCLE = ["-", "--", "-.", ":"]


@dataclass(frozen=True)
class OnlinePoint:
    workload: str
    strategy: str
    dist: str
    configured_rate: float
    request_throughput: float
    mean_ttft_ms: float
    p99_ttft_ms: float
    result_dir: Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot online req/s-TTFT figures for paper usage."
    )
    parser.add_argument(
        "--result-root",
        type=Path,
        default=RESULT_ROOT,
        help="Directory containing online benchmark result subdirectories.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Directory to save generated figures.",
    )
    parser.add_argument(
        "--x-metric",
        choices=["request_throughput", "configured_rate"],
        default="request_throughput",
        help="Metric to use on the x-axis.",
    )
    parser.add_argument(
        "--ttft-metric",
        choices=["mean_ttft_ms", "p99_ttft_ms"],
        default="mean_ttft_ms",
        help="TTFT statistic to use on the y-axis.",
    )
    parser.add_argument(
        "--ttft-ymax",
        type=float,
        default=500.0,
        help="Upper bound of the TTFT axis. Points above it are clipped.",
    )
    parser.add_argument(
        "--workloads",
        nargs="*",
        default=None,
        help="Optional workload filter, e.g. dpsk_24 olmoe_32.",
    )
    return parser.parse_args()


def dist_sort_key(dist: str) -> tuple[int, int]:
    match = DIST_RE.match(dist)
    if not match:
        return (10**9, 10**9)
    return (int(match.group("mean")), int(match.group("std")))


def dist_to_label(dist: str) -> str:
    match = DIST_RE.match(dist)
    if not match:
        return dist
    return f"mu={match.group('mean')}, sigma={match.group('std')}"


def strategy_sort_key(strategy: str) -> tuple[int, str]:
    try:
        return (STRATEGY_ORDER.index(strategy), strategy)
    except ValueError:
        return (len(STRATEGY_ORDER), strategy)


def workload_sort_key(workload: str) -> tuple[int, str]:
    preferred = ["dpsk_24", "olmoe_32"]
    try:
        return (preferred.index(workload), workload)
    except ValueError:
        return (len(preferred), workload)


def load_online_points(result_root: Path) -> list[OnlinePoint]:
    points: list[OnlinePoint] = []
    for result_dir in sorted(result_root.iterdir()):
        if not result_dir.is_dir() or "-online_" not in result_dir.name:
            continue

        match = EXPERIMENT_NAME_RE.match(result_dir.name)
        if not match:
            raise ValueError(f"Unexpected online result directory name: {result_dir.name}")

        json_files = sorted(result_dir.glob("rate_*.json"))
        if len(json_files) != 1:
            raise ValueError(
                f"Expected exactly one rate_*.json in {result_dir}, found {len(json_files)}"
            )

        with json_files[0].open("r", encoding="utf-8") as f:
            data = json.load(f)

        points.append(
            OnlinePoint(
                workload=match.group("workload"),
                strategy=match.group("strategy"),
                dist=match.group("dist"),
                configured_rate=float(data["request_rate"]),
                request_throughput=float(data["request_throughput"]),
                mean_ttft_ms=float(data["mean_ttft_ms"]),
                p99_ttft_ms=float(data["p99_ttft_ms"]),
                result_dir=result_dir,
            )
        )

    if not points:
        raise ValueError(f"No online benchmark results found under {result_root}")
    return points


def group_points(
    points: list[OnlinePoint],
) -> dict[str, dict[tuple[str, str], list[OnlinePoint]]]:
    grouped: dict[str, dict[tuple[str, str], list[OnlinePoint]]] = defaultdict(
        lambda: defaultdict(list)
    )
    for point in points:
        grouped[point.workload][(point.strategy, point.dist)].append(point)
    return grouped


def x_value(point: OnlinePoint, x_metric: str) -> float:
    return (
        point.request_throughput
        if x_metric == "request_throughput"
        else point.configured_rate
    )


def y_value(point: OnlinePoint, ttft_metric: str) -> float:
    return point.mean_ttft_ms if ttft_metric == "mean_ttft_ms" else point.p99_ttft_ms


def axis_labels(x_metric: str, ttft_metric: str) -> tuple[str, str]:
    xlabel = (
        "Request Throughput (req/s)"
        if x_metric == "request_throughput"
        else "Configured Request Rate (req/s)"
    )
    ylabel = "Mean TTFT (ms)" if ttft_metric == "mean_ttft_ms" else "P99 TTFT (ms)"
    return xlabel, ylabel


def make_style_maps(points: list[OnlinePoint]) -> dict[str, str]:
    dists = sorted({point.dist for point in points}, key=dist_sort_key)
    return {
        dist: LINESTYLE_CYCLE[idx % len(LINESTYLE_CYCLE)]
        for idx, dist in enumerate(dists)
    }


def apply_paper_style() -> None:
    plt.rcParams.update(
        {
            "figure.dpi": 180,
            "savefig.dpi": 300,
            "savefig.bbox": "tight",
            "font.size": 11,
            "axes.titlesize": 12,
            "axes.labelsize": 11,
            "legend.fontsize": 9,
            "xtick.labelsize": 10,
            "ytick.labelsize": 10,
            "axes.grid": True,
            "grid.alpha": 0.25,
            "grid.linestyle": "--",
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )


def plot_workload_axis(
    ax: plt.Axes,
    workload: str,
    series_map: dict[tuple[str, str], list[OnlinePoint]],
    x_metric: str,
    ttft_metric: str,
    linestyle_map: dict[str, str],
    ttft_ymax: float | None,
) -> None:
    series_keys = sorted(
        series_map,
        key=lambda item: (strategy_sort_key(item[0]), dist_sort_key(item[1])),
    )
    for strategy, dist in series_keys:
        series = sorted(series_map[(strategy, dist)], key=lambda point: x_value(point, x_metric))
        xs = [x_value(point, x_metric) for point in series]
        ys = [y_value(point, ttft_metric) for point in series]
        label = f"{STRATEGY_LABELS.get(strategy, strategy)} ({dist_to_label(dist)})"
        ax.plot(
            xs,
            ys,
            label=label,
            color=COLOR_MAP.get(strategy, "#333333"),
            marker=MARKER_MAP.get(strategy, "o"),
            linestyle=linestyle_map[dist],
            linewidth=2.2,
            markersize=5.5,
        )

    xlabel, ylabel = axis_labels(x_metric, ttft_metric)
    ax.set_title(workload)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if ttft_ymax is not None:
        ax.set_ylim(0, ttft_ymax)
    ax.margins(x=0.03, y=0.08)


def save_figure(fig: plt.Figure, output_dir: Path, stem: str) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    for suffix in ("png", "pdf"):
        fig.savefig(output_dir / f"{stem}.{suffix}")
    plt.close(fig)


def plot_overview(
    grouped: dict[str, dict[tuple[str, str], list[OnlinePoint]]],
    all_points: list[OnlinePoint],
    output_dir: Path,
    x_metric: str,
    ttft_metric: str,
    ttft_ymax: float | None,
) -> None:
    workloads = sorted(grouped, key=workload_sort_key)
    fig, axes = plt.subplots(1, len(workloads), figsize=(7.0 * len(workloads), 4.6))
    if len(workloads) == 1:
        axes = [axes]

    linestyle_map = make_style_maps(all_points)
    for ax, workload in zip(axes, workloads):
        plot_workload_axis(
            ax=ax,
            workload=workload,
            series_map=grouped[workload],
            x_metric=x_metric,
            ttft_metric=ttft_metric,
            linestyle_map=linestyle_map,
            ttft_ymax=ttft_ymax,
        )

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="upper center",
        ncol=min(4, len(labels)),
        frameon=False,
        bbox_to_anchor=(0.5, 1.06),
    )
    fig.tight_layout(rect=(0.0, 0.0, 1.0, 0.92))
    save_figure(fig, output_dir, f"online_{x_metric}_vs_{ttft_metric}_overview")


def plot_per_workload(
    grouped: dict[str, dict[tuple[str, str], list[OnlinePoint]]],
    all_points: list[OnlinePoint],
    output_dir: Path,
    x_metric: str,
    ttft_metric: str,
    ttft_ymax: float | None,
) -> None:
    linestyle_map = make_style_maps(all_points)
    for workload in sorted(grouped, key=workload_sort_key):
        fig, ax = plt.subplots(figsize=(6.6, 4.4))
        plot_workload_axis(
            ax=ax,
            workload=workload,
            series_map=grouped[workload],
            x_metric=x_metric,
            ttft_metric=ttft_metric,
            linestyle_map=linestyle_map,
            ttft_ymax=ttft_ymax,
        )
        ax.legend(frameon=False, ncol=2)
        fig.tight_layout()
        save_figure(fig, output_dir, f"online_{workload}_{x_metric}_vs_{ttft_metric}")


def main() -> None:
    args = parse_args()
    apply_paper_style()

    points = load_online_points(args.result_root)
    if args.workloads:
        allowed = set(args.workloads)
        points = [point for point in points if point.workload in allowed]
        if not points:
            raise ValueError(f"No matching workloads found for filter: {sorted(allowed)}")

    grouped = group_points(points)

    plot_overview(
        grouped=grouped,
        all_points=points,
        output_dir=args.output_dir,
        x_metric=args.x_metric,
        ttft_metric=args.ttft_metric,
        ttft_ymax=args.ttft_ymax,
    )
    plot_per_workload(
        grouped=grouped,
        all_points=points,
        output_dir=args.output_dir,
        x_metric=args.x_metric,
        ttft_metric=args.ttft_metric,
        ttft_ymax=args.ttft_ymax,
    )

    print(f"Saved figures to {args.output_dir}")


if __name__ == "__main__":
    main()
