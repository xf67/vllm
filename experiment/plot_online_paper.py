#!/usr/bin/env python3
"""Generate paper-style matplotlib plots for online benchmark results.

This script scans benchmark result directories generated by the online
experiments, parses condition names from directory names, and plots:

1. Single-metric figures, including an overview and one figure per workload.
2. Multi-metric figures with horizontally arranged subplots and a shared legend.

Each line corresponds to one online test condition. Colors are reserved for
different scheduling strategies, while line styles distinguish different QoS
distribution settings.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


RESULT_ROOT = Path("/home/xxf/NewVLLM/vllm/test-vllm-merged/bench_results")
DEFAULT_OUTPUT_DIR = Path("/home/xxf/NewVLLM/vllm/test-vllm-merged/paper_figs/online")

EXPERIMENT_NAME_RE = re.compile(
    r"^(?P<workload>.+)-online_(?P<strategy>[^-]+)-(?P<dist>m\d+s\d+)-r(?P<rate>.+)$"
)
DIST_RE = re.compile(r"^m(?P<mean>\d+)s(?P<std>\d+)$")

STRATEGY_LABELS = {
    "ours": "Ours",
    "vllmD": "vllm-DP",
    "vllmK": "vLLM + QoS",
    "vllmT": "vllm-TP",
    "vllmTE": "vllm-TPEP",
}

PLOT_STRATEGIES = {"ours", "vllmD", "vllmT", "vllmTE"}
PLOT_DISTS = {"m12s3", "m16s5"}
STRATEGY_ORDER = ["ours", "vllmD", "vllmT", "vllmTE"]
COLOR_MAP = {
    "ours": "#d62728",
    "vllmK": "#1f77b4",
    "vllmD": "#ebb52c",
    "vllmT": "#6796bd",
    "vllmTE": "#00ccb7ff",
}
MARKER_MAP = {
    "ours": "o",
    "vllmK": "s",
    "vllmD": "^",
    "vllmT": "D",
    "vllmTE": "P",
}
LINESTYLE_CYCLE = ["-"] #, "--", "-.", ":"
METRIC_ALIASES = {
    "ttft_mean": "mean_ttft_ms",
    "ttft_median": "median_ttft_ms",
    "ttft_p75": "p75_ttft_ms",
    "ttft_p90": "p90_ttft_ms",
    "ttft_p95": "p95_ttft_ms",
    "ttft_p99": "p99_ttft_ms",
    "tpot_mean": "mean_tpot_ms",
    "tpot_p75": "p75_tpot_ms",
    "tpot_p90": "p90_tpot_ms",
    "tpot_p95": "p95_tpot_ms",
    "tpot_p99": "p99_tpot_ms",
}


@dataclass(frozen=True)
class OnlinePoint:
    workload: str
    strategy: str
    dist: str
    configured_rate: float
    result_dir: Path
    metrics: dict[str, object]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot online req/s-TTFT figures for paper usage."
    )
    parser.add_argument(
        "--result-root",
        type=Path,
        default=RESULT_ROOT,
        help="Directory containing online benchmark result subdirectories.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Directory to save generated figures.",
    )
    parser.add_argument(
        "--x-metric",
        default="request_rate",
        help="Metric to use on the x-axis. Supports JSON keys or 'configured_rate'.",
    )
    parser.add_argument(
        "--y-metric",
        "--ttft-metric",
        dest="y_metric",
        default="mean_ttft_ms",
        help="Metric to use on the y-axis. Supports any numeric JSON key.",
    )
    parser.add_argument(
        "--y-metrics",
        nargs="+",
        default=None,
        help=(
            "Multiple y-axis metrics for one horizontally arranged figure. "
            "Supports aliases like ttft_p99 ttft_p90 ttft_p75 ttft_mean."
        ),
    )
    parser.add_argument(
        "--ymax",
        "--ttft-ymax",
        dest="ymax",
        type=float,
        default=700.0,
        help="Upper bound of the y-axis. Points above it are clipped.",
    )
    parser.add_argument(
        "--workloads",
        nargs="*",
        default=None,
        help="Optional workload filter, e.g. dpsk_24 olmoe_32.",
    )
    return parser.parse_args()


def dist_sort_key(dist: str) -> tuple[int, int]:
    match = DIST_RE.match(dist)
    if not match:
        return (10**9, 10**9)
    return (int(match.group("mean")), int(match.group("std")))


def dist_to_label(dist: str) -> str:
    match = DIST_RE.match(dist)
    if not match:
        return dist
    return f"{match.group('mean')}/{match.group('std')}"


def canonicalize_metric_name(metric_name: str) -> str:
    return METRIC_ALIASES.get(metric_name, metric_name)


def canonicalize_metric_names(metric_names: list[str]) -> list[str]:
    return [canonicalize_metric_name(metric_name) for metric_name in metric_names]


def strategy_sort_key(strategy: str) -> tuple[int, str]:
    try:
        return (STRATEGY_ORDER.index(strategy), strategy)
    except ValueError:
        return (len(STRATEGY_ORDER), strategy)


def workload_sort_key(workload: str) -> tuple[int, str]:
    preferred = ["dpsk_24", "olmoe_32"]
    try:
        return (preferred.index(workload), workload)
    except ValueError:
        return (len(preferred), workload)


def load_online_points(result_root: Path) -> list[OnlinePoint]:
    points: list[OnlinePoint] = []
    for result_dir in sorted(result_root.iterdir()):
        if not result_dir.is_dir() or "-online_" not in result_dir.name:
            continue

        match = EXPERIMENT_NAME_RE.match(result_dir.name)
        if not match:
            raise ValueError(f"Unexpected online result directory name: {result_dir.name}")

        json_files = sorted(result_dir.glob("rate_*.json"))
        if not json_files:
            print(f"[WARN] Skip empty result directory: {result_dir}")
            continue
        if len(json_files) != 1:
            raise ValueError(
                f"Expected exactly one rate_*.json in {result_dir}, found {len(json_files)}"
            )

        with json_files[0].open("r", encoding="utf-8") as f:
            data = json.load(f)

        points.append(
            OnlinePoint(
                workload=match.group("workload"),
                strategy=match.group("strategy"),
                dist=match.group("dist"),
                configured_rate=float(data["request_rate"]),
                result_dir=result_dir,
                metrics=data,
            )
        )

    if not points:
        raise ValueError(f"No online benchmark results found under {result_root}")
    return points


def group_points(
    points: list[OnlinePoint],
) -> dict[str, dict[tuple[str, str], list[OnlinePoint]]]:
    grouped: dict[str, dict[tuple[str, str], list[OnlinePoint]]] = defaultdict(
        lambda: defaultdict(list)
    )
    for point in points:
        grouped[point.workload][(point.strategy, point.dist)].append(point)
    return grouped


def metric_value(point: OnlinePoint, metric_name: str) -> float:
    if metric_name in {"configured_rate", "request_rate"}:
        return point.configured_rate

    if metric_name not in point.metrics:
        available = ", ".join(sorted(point.metrics.keys()))
        raise KeyError(
            f"Metric '{metric_name}' not found in {point.result_dir}. "
            f"Available keys: {available}"
        )

    value = point.metrics[metric_name]
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(
            f"Metric '{metric_name}' in {point.result_dir} is not numeric: {type(value).__name__}"
        )
    return float(value)


def metric_label(metric_name: str) -> str:
    metric_name = canonicalize_metric_name(metric_name)
    common_labels = {
        "configured_rate": "Request Rate (req/s)",
        "request_rate": "Request Rate (req/s)",
        "request_throughput": "Request Throughput (req/s)",
        "output_throughput": "Output Throughput (tok/s)",
        "total_token_throughput": "Total Token Throughput (tok/s)",
        "mean_ttft_ms": "Mean TTFT (ms)",
        "median_ttft_ms": "Median TTFT (ms)",
        "p75_ttft_ms": "P75 TTFT (ms)",
        "p90_ttft_ms": "P90 TTFT (ms)",
        "p95_ttft_ms": "P95 TTFT (ms)",
        "p99_ttft_ms": "P99 TTFT (ms)",
        "mean_tpot_ms": "Mean TPOT (ms)",
        "median_tpot_ms": "Median TPOT (ms)",
        "p75_tpot_ms": "P75 TPOT (ms)",
        "p90_tpot_ms": "P90 TPOT (ms)",
        "p95_tpot_ms": "P95 TPOT (ms)",
        "p99_tpot_ms": "P99 TPOT (ms)",
        "mean_itl_ms": "Mean ITL (ms)",
        "median_itl_ms": "Median ITL (ms)",
        "p75_itl_ms": "P75 ITL (ms)",
        "p90_itl_ms": "P90 ITL (ms)",
        "p95_itl_ms": "P95 ITL (ms)",
        "p99_itl_ms": "P99 ITL (ms)",
    }
    if metric_name in common_labels:
        return common_labels[metric_name]
    return metric_name.replace("_", " ")


def axis_labels(x_metric: str, y_metric: str) -> tuple[str, str]:
    return metric_label(x_metric), metric_label(y_metric)


def metric_stem(metric_name: str) -> str:
    metric_name = canonicalize_metric_name(metric_name)
    return metric_name.replace("_", "-")


def make_style_maps(points: list[OnlinePoint]) -> dict[str, str]:
    dists = sorted({point.dist for point in points}, key=dist_sort_key)
    return {
        dist: LINESTYLE_CYCLE[idx % len(LINESTYLE_CYCLE)]
        for idx, dist in enumerate(dists)
    }


def unique_legend_entries(
    axes: list[plt.Axes],
) -> tuple[list[object], list[str]]:
    handles: list[object] = []
    labels: list[str] = []
    seen: set[str] = set()
    for ax in axes:
        axis_handles, axis_labels = ax.get_legend_handles_labels()
        for handle, label in zip(axis_handles, axis_labels):
            if not label or label in seen:
                continue
            seen.add(label)
            handles.append(handle)
            labels.append(label)
    return handles, labels


def apply_paper_style() -> None:
    plt.rcParams.update(
        {
            "figure.dpi": 180,
            "savefig.dpi": 300,
            "savefig.bbox": "tight",
            "font.size": 20,
            "axes.titlesize": 22,
            "axes.labelsize": 21,
            "legend.fontsize": 19,
            "xtick.labelsize": 19,
            "ytick.labelsize": 19,
            "axes.grid": True,
            "grid.alpha": 0.25,
            "grid.linestyle": "--",
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )


def plot_workload_axis(
    ax: plt.Axes,
    workload: str,
    series_map: dict[tuple[str, str], list[OnlinePoint]],
    x_metric: str,
    y_metric: str,
    linestyle_map: dict[str, str],
    ymax: float | None,
) -> None:
    series_keys = sorted(
        series_map,
        key=lambda item: (strategy_sort_key(item[0]), dist_sort_key(item[1])),
    )
    all_y_values: list[float] = []
    for strategy, dist in series_keys:
        series = sorted(
            series_map[(strategy, dist)],
            key=lambda point: metric_value(point, x_metric),
        )
        xs = [metric_value(point, x_metric) for point in series]
        ys = [metric_value(point, y_metric) for point in series]
        all_y_values.extend(ys)
        label = STRATEGY_LABELS.get(strategy, strategy)
        ax.plot(
            xs,
            ys,
            label=label,
            color=COLOR_MAP.get(strategy, "#333333"),
            marker=MARKER_MAP.get(strategy, "o"),
            linestyle=linestyle_map[dist],
            linewidth=2.4,
            markersize=6.5,
        )

    xlabel, ylabel = axis_labels(x_metric, y_metric)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if all_y_values:
        min_y = min(all_y_values)
        lower = min_y * 0.9 if min_y > 0 else min_y
        if ymax is not None:
            upper = ymax
            if lower >= upper:
                lower = upper * 0.95
            ax.set_ylim(lower, upper)
        else:
            ax.set_ylim(bottom=lower)
    ax.margins(x=0.03, y=0.08)


def save_figure(fig: plt.Figure, output_dir: Path, stem: str) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    for suffix in ("png", "pdf"):
        fig.savefig(output_dir / f"{stem}.{suffix}")
    plt.close(fig)


def plot_overview(
    grouped: dict[str, dict[tuple[str, str], list[OnlinePoint]]],
    all_points: list[OnlinePoint],
    output_dir: Path,
    x_metric: str,
    y_metric: str,
    ymax: float | None,
) -> None:
    workloads = sorted(grouped, key=workload_sort_key)
    fig, axes = plt.subplots(1, len(workloads), figsize=(6.6 * len(workloads), 3.2))
    if len(workloads) == 1:
        axes = [axes]

    linestyle_map = make_style_maps(all_points)
    for ax, workload in zip(axes, workloads):
        plot_workload_axis(
            ax=ax,
            workload=workload,
            series_map=grouped[workload],
            x_metric=x_metric,
            y_metric=y_metric,
            linestyle_map=linestyle_map,
            ymax=ymax,
        )

    handles, labels = unique_legend_entries(axes)
    fig.legend(
        handles,
        labels,
        loc="center left",
        ncol=1,
        frameon=False,
        bbox_to_anchor=(0.915, 0.5),
    )
    fig.tight_layout(rect=(0.0, 0.0, 0.89, 1.0))
    save_figure(fig, output_dir, f"online_{x_metric}_vs_{y_metric}_overview")


def plot_per_workload_multi_metrics(
    grouped: dict[str, dict[tuple[str, str], list[OnlinePoint]]],
    all_points: list[OnlinePoint],
    output_dir: Path,
    x_metric: str,
    y_metrics: list[str],
    ymax: float | None,
) -> None:
    linestyle_map = make_style_maps(all_points)
    for workload in sorted(grouped, key=workload_sort_key):
        # Keep the full row at a 2n:1.2 aspect ratio.
        fig, axes = plt.subplots(1, len(y_metrics), figsize=(6.0 * len(y_metrics), 3.0))
        if len(y_metrics) == 1:
            axes = [axes]
        else:
            axes = list(axes)

        for ax, y_metric in zip(axes, y_metrics):
            plot_workload_axis(
                ax=ax,
                workload=workload,
                series_map=grouped[workload],
                x_metric=x_metric,
                y_metric=y_metric,
                linestyle_map=linestyle_map,
                ymax=ymax,
            )

        handles, labels = unique_legend_entries(axes)
        fig.legend(
            handles,
            labels,
            loc="center left",
            ncol=1,
            frameon=False,
            bbox_to_anchor=(0.915, 0.5),
        )
        fig.tight_layout(rect=(0.0, 0.0, 0.89, 1.0))
        metric_suffix = "_".join(metric_stem(metric_name) for metric_name in y_metrics)
        save_figure(fig, output_dir, f"online_{workload}_{x_metric}_vs_{metric_suffix}")


def plot_per_workload(
    grouped: dict[str, dict[tuple[str, str], list[OnlinePoint]]],
    all_points: list[OnlinePoint],
    output_dir: Path,
    x_metric: str,
    y_metric: str,
    ymax: float | None,
) -> None:
    linestyle_map = make_style_maps(all_points)
    for workload in sorted(grouped, key=workload_sort_key):
        fig, ax = plt.subplots(figsize=(9.0, 3.0))
        plot_workload_axis(
            ax=ax,
            workload=workload,
            series_map=grouped[workload],
            x_metric=x_metric,
            y_metric=y_metric,
            linestyle_map=linestyle_map,
            ymax=ymax,
        )
        ax.legend(
            frameon=False,
            ncol=1,
            loc="center left",
            bbox_to_anchor=(1.005, 0.5),
            borderaxespad=0.0,
        )
        fig.tight_layout(rect=(0.0, 0.0, 0.86, 1.0))
        save_figure(fig, output_dir, f"online_{workload}_{x_metric}_vs_{y_metric}")


def main() -> None:
    args = parse_args()
    apply_paper_style()
    x_metric = canonicalize_metric_name(args.x_metric)
    y_metrics = (
        canonicalize_metric_names(args.y_metrics)
        if args.y_metrics
        else [canonicalize_metric_name(args.y_metric)]
    )

    points = load_online_points(args.result_root)
    points = [point for point in points if point.strategy in PLOT_STRATEGIES]
    if not points:
        raise ValueError(
            "No online benchmark results remain after filtering plotted strategies."
        )
    points = [point for point in points if point.dist in PLOT_DISTS]
    if not points:
        raise ValueError(
            "No online benchmark results remain after filtering plotted distributions."
        )
    if args.workloads:
        allowed = set(args.workloads)
        points = [point for point in points if point.workload in allowed]
        if not points:
            raise ValueError(f"No matching workloads found for filter: {sorted(allowed)}")

    grouped = group_points(points)

    if len(y_metrics) == 1:
        plot_overview(
            grouped=grouped,
            all_points=points,
            output_dir=args.output_dir,
            x_metric=x_metric,
            y_metric=y_metrics[0],
            ymax=args.ymax,
        )
        plot_per_workload(
            grouped=grouped,
            all_points=points,
            output_dir=args.output_dir,
            x_metric=x_metric,
            y_metric=y_metrics[0],
            ymax=args.ymax,
        )
    else:
        plot_per_workload_multi_metrics(
            grouped=grouped,
            all_points=points,
            output_dir=args.output_dir,
            x_metric=x_metric,
            y_metrics=y_metrics,
            ymax=args.ymax,
        )

    print(f"Saved figures to {args.output_dir}")


if __name__ == "__main__":
    main()


